const { chromium } = require('C:/Users/Huy/.bun/install/cache/playwright-core@1.64.1@@@1');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Users/Huy/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe', headless: true, args: ['--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1905, height: 872 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000/trien-lam-1975');
  await page.waitForFunction(() => Boolean(document.querySelector('canvas')));
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await page.waitForTimeout(1200);
  const look = async dy => page.evaluate(dy => {
    const event = new PointerEvent('pointermove');
    Object.defineProperties(event, { movementX: { value: 0 }, movementY: { value: dy } });
    document.dispatchEvent(event);
  }, dy);
  await look(-65);
  await page.waitForTimeout(300);
  await page.screenshot({ path: '.run/exhibition-reference-view.png' });
  await look(240);
  await page.waitForTimeout(300);
  await page.screenshot({ path: '.run/exhibition-reference-floor.png' });
  await look(-520);
  await page.waitForTimeout(300);
  await page.screenshot({ path: '.run/exhibition-reference-ceiling.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: 'Một khoảng lặng.' }).waitFor();
  await page.screenshot({ path: '.run/exhibition-reference-pause.png' });
  console.log({ errors, viewport: '1905x872', captures: ['view', 'floor', 'ceiling', 'pause'] });
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
