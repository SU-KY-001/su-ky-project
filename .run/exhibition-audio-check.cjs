const { chromium } = require('C:/Users/Huy/.bun/install/cache/playwright-core@1.64.1@@@1');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Users/Huy/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe', headless: true, args: ['--enable-unsafe-swiftshader'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000/trien-lam-1975');
  await page.waitForFunction(() => Boolean(document.querySelector('canvas')));
  const before = await page.locator('audio').evaluate(audio => ({ paused: audio.paused, currentTime: audio.currentTime, preload: audio.preload, src: decodeURIComponent(audio.src) }));
  if (!before.paused || before.currentTime !== 0 || !before.src.includes('audio-trienlam-3d')) throw new Error('Incorrect soundtrack or playing before Enter');
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await page.waitForFunction(() => { const audio = document.querySelector('audio'); return !audio.paused && audio.currentTime > 0.4 && !audio.error; }, { timeout: 20000 });
  await page.keyboard.press('m');
  await page.getByRole('dialog').waitFor();
  if (await page.locator('audio').evaluate(audio => audio.paused)) throw new Error('Soundtrack should continue while viewing the catalog');
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: 'Một khoảng lặng.' }).waitFor();
  await page.waitForFunction(() => document.querySelector('audio').paused);
  const pausedAt = await page.locator('audio').evaluate(audio => audio.currentTime);
  await page.getByRole('button', { name: 'Tiếp tục tham quan' }).click();
  await page.waitForFunction(time => { const audio = document.querySelector('audio'); return !audio.paused && audio.currentTime > time + 0.2; }, pausedAt);
  console.log({ initialPaused: before.paused, sourceFolder: 'audio-trienlam-3d', catalogContinues: true, pauseAndResume: true, volume: await page.locator('audio').evaluate(audio => audio.volume), errors });
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
